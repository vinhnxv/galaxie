import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

function serialize(schema: object): string {
  return `${JSON.stringify(schema, null, 2)}\n`;
}

/** Write the generated editor schema; no copy is kept in source control. */
export function writeHostConfigSchema(schema: object, target: string): void {
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, serialize(schema));
}

/** Compare exact generated bytes without rewriting the artifact. */
export function verifyHostConfigSchema(schema: object, target: string): void {
  if (readFileSync(target, 'utf8') !== serialize(schema))
    throw new Error('Host configuration schema mismatch.');
}

if (import.meta.main) {
  try {
    const args = process.argv.slice(2);
    if (args.length > 1 || (args.length === 1 && args[0] !== '--verify'))
      throw new Error('Usage: node scripts/build-host-config-schema.ts [--verify]');
    const moduleURL = new URL('../packages/core/dist/config/index.js', import.meta.url);
    const { hostConfigJsonSchema } = (await import(moduleURL.href)) as {
      hostConfigJsonSchema: () => object;
    };
    const target = fileURLToPath(
      new URL('../packages/core/dist/config/host-config.schema.json', import.meta.url),
    );
    if (args[0] === '--verify') verifyHostConfigSchema(hostConfigJsonSchema(), target);
    else writeHostConfigSchema(hostConfigJsonSchema(), target);
  } catch (error) {
    console.error(
      error instanceof Error ? error.message : 'Host configuration schema operation failed.',
    );
    process.exitCode = 1;
  }
}
